import { expect, test } from '@playwright/test';
import { installMockApi } from './mockApi';

test('opens Knowledge Base from sidebar and creates rated manual data', async ({ page }) => {
	await installMockApi(page);
	await page.goto('/');
	await page.getByRole('button', { name: 'База знаний' }).click();
	await expect(page).toHaveURL(/\/knowledge/);
	await expect(page.getByRole('button', { name: 'База знаний' })).toHaveAttribute('aria-current', 'page');
	await page.getByRole('button', { name: 'Добавить данные' }).click();
	const dialog = page.getByRole('dialog');
	const formStars = dialog.locator('.rating__star svg');
	await expect(formStars).toHaveCount(5);
	const starRendering = await formStars.first().evaluate((svg) => {
		const box = svg.getBoundingClientRect();
		const style = getComputedStyle(svg);
		const buttonStyle = getComputedStyle(svg.closest('button')!);
		return { width: box.width, height: box.height, display: style.display, opacity: style.opacity, stroke: style.stroke, buttonPadding: buttonStyle.padding, buttonBorderWidth: buttonStyle.borderWidth };
	});
	expect(starRendering).toMatchObject({ width: 18, height: 18, display: 'block', opacity: '1', buttonPadding: '0px', buttonBorderWidth: '0px' });
	expect(starRendering.stroke).not.toBe('none');
	await dialog.getByRole('button', { name: 'Поставить рейтинг 3 из 5' }).hover();
	await expect(dialog.locator('.rating__star--active')).toHaveCount(3);
	await dialog.getByLabel('Название').fill('Проверенный оффер');
	await dialog.getByLabel('Содержимое').fill('Текст для внутренней базы знаний');
	await dialog.getByLabel('Новое значение Подход').fill('UGC-разбор');
	await dialog.locator('.knowledge-form__metadata-row').filter({ hasText: 'Подход' }).getByRole('button', { name: 'Добавить' }).click();
	await dialog.getByRole('button', { name: 'Поставить рейтинг 3 из 5' }).click();
	await dialog.locator('.modal-dialog__confirm').click();
	await expect(page.getByText('Проверенный оффер')).toBeVisible();
	await expect(page.getByRole('img', { name: /Рейтинг Проверенный оффер: 3 из 5/ })).toBeVisible();
	await expect(page.getByText('3/5')).toBeVisible();
	await expect(page.getByText('Подход: UGC-разбор')).toBeVisible();
	await expect(page.getByRole('checkbox', { name: 'Использовать' })).toBeChecked();
	await page.reload();
	await expect(page.getByRole('img', { name: /Рейтинг Проверенный оффер: 3 из 5/ })).toBeVisible();
	await page.getByRole('button', { name: 'Редактировать' }).click();
	const editDialog = page.getByRole('dialog');
	await expect(editDialog.locator('.rating__star svg')).toHaveCount(5);
	await expect(editDialog.locator('.rating__star--active')).toHaveCount(3);
	await expect(editDialog.locator('.rating__star--inactive')).toHaveCount(2);
	await editDialog.getByRole('button', { name: 'Поставить рейтинг 5 из 5' }).click();
	await editDialog.getByRole('button', { name: 'Сохранить' }).click();
	await expect(page.getByRole('img', { name: /Рейтинг Проверенный оффер: 5 из 5/ })).toBeVisible();
	await page.reload();
	await expect(page.getByText('5/5')).toBeVisible();
	await page.locator('label.checkbox').filter({ hasText: 'Использовать' }).click();
	await expect(page.getByRole('checkbox', { name: 'Использовать' })).not.toBeChecked();
	await page.reload();
	await expect(page.getByRole('checkbox', { name: 'Использовать' })).not.toBeChecked();
	const filterRequest = page.waitForRequest((request) => request.url().includes('min_rating=4'));
	await page.getByLabel('Рейтинг', { exact: true }).selectOption('4');
	await filterRequest;
	await page.getByLabel('Источник').selectOption('manual');
	await page.getByLabel('Подход', { exact: true }).selectOption({ label: 'UGC-разбор' });
	await page.getByLabel('Сортировка').selectOption('rating_desc');
	await page.getByLabel('Использование').selectOption('inactive');
	await page.getByLabel('Поиск по базе знаний').fill('оффер');
	await expect(page).toHaveURL(/q=%D0%BE%D1%84%D1%84%D0%B5%D1%80/);
	await page.getByRole('button', { name: 'Сбросить' }).click();
	await expect(page).toHaveURL(/\/knowledge$/);
	await expect(page.getByRole('button', { name: 'Сбросить' })).toBeDisabled();
});

test('creates a custom filter, preserves Markdown and renders preview without duplicating title', async ({ page }) => {
	await installMockApi(page);
	await page.goto('/knowledge');
	await page.getByRole('button', { name: '+ Добавить фильтр' }).click();
	await page.getByLabel('Название нового фильтра').fill('ГЕО');
	await page.locator('.knowledge-page__filter-creator').getByRole('button', { name: 'Создать' }).click();
	await page.getByRole('button', { name: 'Добавить данные' }).click();
	const dialog = page.getByRole('dialog');
	await dialog.getByLabel('Название').fill('Тихий вечер');
	await dialog.getByLabel('Содержимое').fill('**1. Тихий вечер**\n\nОсновной текст.');
	await dialog.getByLabel('Новое значение ГЕО').fill('Бразилия');
	await dialog.locator('.knowledge-form__metadata-row').filter({ hasText: 'ГЕО' }).getByRole('button', { name: 'Добавить' }).click();
	await dialog.getByRole('button', { name: 'Предпросмотр' }).click();
	await expect(dialog.locator('strong').filter({ hasText: '1. Тихий вечер' })).toBeVisible();
	await dialog.locator('.modal-dialog__confirm').click();
	await expect(page.getByText('ГЕО: Бразилия')).toBeVisible();
	await page.getByRole('button', { name: 'Редактировать' }).click();
	const edit = page.getByRole('dialog');
	await expect(edit.getByLabel('Название')).toHaveValue('Тихий вечер');
	await expect(edit.getByLabel('Содержимое')).toHaveValue('**1. Тихий вечер**\n\nОсновной текст.');
});

test('agent can browse and search the current user knowledge through chat', async ({ page }) => {
	await installMockApi(page);
	await page.goto('/knowledge');
	await page.getByRole('button', { name: 'Добавить данные' }).click();
	const dialog = page.getByRole('dialog');
	await dialog.getByLabel('Название').fill('Facebook Hooks');
	await dialog.getByLabel('Содержимое').fill('Для health-офферов используем curiosity angle.');
	await dialog.locator('.modal-dialog__confirm').click();

	await page.getByRole('button', { name: 'Новый чат' }).click();
	await page.getByRole('textbox', { name: 'Введите запрос' }).fill('Что находится в моей базе знаний?');
	await page.getByRole('button', { name: 'Отправить сообщение' }).click();
	await expect(page.getByText(/В вашей базе знаний: Facebook Hooks/)).toBeVisible();

	await page.getByLabel('Открыть меню действий').click();
	await page.getByRole('menuitemradio', { name: 'Поиск по базе знаний' }).click();
	await page.getByRole('textbox', { name: 'Введите запрос' }).pressSequentially('Какой angle использовать для health Facebook?');
	const send = page.getByRole('button', { name: 'Отправить сообщение' });
	await expect(send).toBeEnabled();
	await send.click();
	await expect(page.getByText(/curiosity angle/)).toBeVisible();
});
